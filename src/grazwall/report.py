"""Report building. All server-derived strings are untrusted: they are length-capped,
control/bidi characters are made visible, and everything is HTML-escaped. The HTML report
ships a strict CSP (no scripts at all) so even an escaping bug cannot execute code."""
import datetime
import html
import re

from .checks import ALL_CHECKS, SEV_WEIGHT

VERSION = "0.4.0"
MAX_FIELD = 2000
_CTRL = re.compile(r"[\x00-\x08\x0b-\x1f\x7f-\x9f\u200b-\u200f\u202a-\u202e\u2060-\u2064\ufeff\U000e0000-\U000e007f]")


def clean(s, n=MAX_FIELD):
    """Make an untrusted value safe for text sinks (terminal, JSON, HTML-before-escape)."""
    s = "" if s is None else str(s)
    s = _CTRL.sub(lambda m: "\\u%04x" % ord(m.group(0)) if ord(m.group(0)) < 0x10000 else "\\U%08x" % ord(m.group(0)), s)
    return s if len(s) <= n else s[:n] + "…[truncated]"


def score(findings):
    pen = sum(SEV_WEIGHT.get(f.severity, 0) for f in findings)
    return max(0, 100 - pen)


def grade(s):
    return "A" if s >= 90 else "B" if s >= 75 else "C" if s >= 60 else "D" if s >= 40 else "F"


def build(target, server_info, tools, findings, meta=None):
    s = score(findings)
    counts = {k: sum(1 for f in findings if f.severity == k) for k in SEV_WEIGHT}
    fl = []
    for f in findings:
        d = f.to_dict()
        fl.append({k: (clean(v) if isinstance(v, str) or v is None and k == "tool" else v) if k != "tool" or v else None
                   for k, v in d.items()})
    return {"tool": "grazwall", "version": VERSION, "target": clean(target, 500),
            "scanned_at": datetime.datetime.now().astimezone().isoformat(timespec="seconds"),
            "server": {k: clean(v, 200) for k, v in (server_info or {}).items()},
            "tool_count": len(tools), "checks_run": len(ALL_CHECKS),
            "score": s, "grade": grade(s), "counts": counts, "meta": meta or {}, "findings": fl}


COLORS = {"critical": "#b00020", "high": "#e65100", "medium": "#f9a825", "low": "#1565c0", "info": "#666"}
GC = {"A": "#2e7d32", "B": "#558b2f", "C": "#f9a825", "D": "#e65100", "F": "#b00020"}


def _e(x, n=MAX_FIELD):
    return html.escape(clean(x, n), quote=True)


def to_html(r):
    rows = []
    for f in r["findings"]:
        sev = f.get("severity") if f.get("severity") in COLORS else "info"
        rows.append(
            f"<tr><td>{_e(f.get('check_id'))}</td><td><span class='sev {sev}'>{sev}</span></td>"
            f"<td>{_e(f.get('title'))}</td><td><code>{_e(f.get('tool') or '-')}</code></td>"
            f"<td>{_e(f.get('detail'))}<br><small>Evidence: <code>{_e(f.get('evidence'))}</code></small></td>"
            f"<td>{_e(f.get('remediation'))}</td></tr>")
    c = r["counts"]
    g = r["grade"] if r["grade"] in GC else "F"
    sevcss = "".join(f".{k}{{background:{v}}}" for k, v in COLORS.items())
    srv = r.get("server") or {}
    meta = r.get("meta") or {}
    return f"""<!doctype html><html><head><meta charset=utf-8>
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; img-src 'none'; form-action 'none'; base-uri 'none'">
<meta name="referrer" content="no-referrer"><title>Grazwall report</title>
<style>body{{font-family:system-ui,sans-serif;margin:2rem;color:#222}}table{{border-collapse:collapse;width:100%}}
td,th{{border-bottom:1px solid #ddd;padding:.5rem;vertical-align:top;text-align:left;font-size:14px;word-break:break-word}}
.sev{{color:#fff;padding:2px 8px;border-radius:4px;font-size:12px}}{sevcss}.grade{{font-size:64px;font-weight:700;color:{GC[g]}}}
.box{{display:flex;gap:2rem;align-items:center}}code{{background:#f4f4f4;padding:1px 4px;white-space:pre-wrap}}</style></head><body>
<h1>Grazwall security report</h1>
<div class=box><div class=grade>{g}</div><div><b>Score:</b> {int(r['score'])}/100<br>
<b>Target:</b> <code>{_e(r['target'], 500)}</code><br><b>Server:</b> {_e(srv.get('name', '?'), 200)} {_e(srv.get('version', ''), 200)}<br>
<b>Tools:</b> {int(r['tool_count'])} &middot; <b>Checks:</b> {int(r['checks_run'])} &middot; <b>Sandbox:</b> {_e(meta.get('sandbox', '?'), 50)} &middot; <b>Profile:</b> {_e(','.join(meta.get('profiles') or []) or 'none', 100)} &middot; <b>Scanned:</b> {_e(r['scanned_at'], 50)}<br>
critical {int(c['critical'])} &middot; high {int(c['high'])} &middot; medium {int(c['medium'])} &middot; low {int(c['low'])}</div></div>
<h2>Findings ({len(r['findings'])})</h2>
<table><tr><th>ID</th><th>Severity</th><th>Finding</th><th>Tool</th><th>Detail</th><th>Fix</th></tr>{''.join(rows) or '<tr><td colspan=6>No findings.</td></tr>'}</table>
<p><small>Generated by Grazwall {VERSION}. Static + live probes; findings are heuristic, verify before disclosure.</small></p></body></html>"""
